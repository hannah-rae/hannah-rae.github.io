#!/usr/bin/env python3
"""Sync _data/publications.yml and files/bibtex/ from the CV PDF.

The CV (files/Kerner_Hannah_CV.pdf) is the source of truth. Each run:
  1. extracts the numbered entries from the CV's PUBLICATIONS sections,
  2. matches them to existing YAML entries (by title + CV section, then fuzzy
     title), keeping each entry's id and the fields you maintain by hand:
     venue (short label), code, site, data, thumb_image, thumb_class,
  3. refreshes the CV-derived fields: title, authors, venue_full, type, year,
     award, paper,
  4. flags `recent: true` on the newest RECENT_COUNT entries that have a paper URL,
  5. rewrites every /files/bibtex/<id>.bib from the CV fields,
  6. cross-checks the result against the CV text and fails loudly on mismatch.

New papers get an auto-generated id and short venue label; both are printed so
you can review them (edit `venue` in the YAML freely, it is kept on later runs
unless the CV venue changes, e.g. when a preprint gets accepted).

Usage (from the repo root):
  pip install -r scripts/requirements.txt
  python scripts/sync_publications.py               # sync
  python scripts/sync_publications.py --dry-run     # show what would change
  python scripts/sync_publications.py --thumbnails  # sync, then make thumbnails for
                                                    # every paper still missing one
"""
import argparse
import difflib
import json
import re
import sys
import unicodedata
from pathlib import Path

import pypdf
import yaml

REPO = Path(__file__).resolve().parent.parent
CV = REPO / "files" / "Kerner_Hannah_CV.pdf"
PUBS = REPO / "_data" / "publications.yml"
BIB_DIR = REPO / "files" / "bibtex"
RECENT_COUNT = 5

# CV section headings (compared with spaces removed, lowercase) -> type
SECTIONS = [
    ("preprintsunderreview", "preprint"),
    ("peer-reviewedconferenceproceedings", "conference"),
    ("peer-reviewedjournalarticles", "journal"),
    ("peer-reviewedconferenceworkshops", "workshop"),
    ("booksandbookchapters", "book"),
    ("whitepapersandotherpublications", "other"),
]
START, END = "Preprints Under Review", "Editing"
HAND_FIELDS = ("code", "site", "data", "thumb_image", "thumb_class")

HEADER = """\
# All publications, ordered as shown on /publications/ (newest year first;
# within a year, the order they appear in the CV).
#
# GENERATED by scripts/sync_publications.py from files/Kerner_Hannah_CV.pdf.
# Edit the CV and re-run the script rather than editing CV-derived fields here.
# Fields you can edit by hand (kept across syncs): venue, code, site, data,
# thumb_image, thumb_class.
#
# Fields:
#   id          : bibkey (matches /files/bibtex/<id>.bib); also the anchor id
#   recent      : set automatically on the newest {n} entries with a `paper` URL;
#                 these are featured in the home page "Recent work" list
#   title       : paper title (from CV)
#   authors     : author list (from CV)
#   venue       : compact venue + year shown on the site (e.g. "ICML 2025")
#   venue_full  : full venue text (from CV; used for bibtex)
#   type        : CV section: preprint | conference | journal | workshop | book | other
#   year        : integer (from CV)
#   award       : award/spotlight tag (from CV, optional)
#   paper       : URL to paper (from CV, optional)
#   code, site, data : extra links (optional)
#   thumb_image : thumbnail under /images/ (optional; see scripts/paper_thumbnails.py)
#   thumb_class : placeholder gradient class when no thumb_image (optional)
#   bibtex      : path to the .bib file
""".format(n=RECENT_COUNT)


def nospace(s):
    return re.sub(r"\s+", "", s)


def norm_title(t):
    return re.sub(r"[^a-z0-9]", "", t.lower())


# ------------------------------------------------------------------ CV parsing
def cv_text():
    return "\n".join(p.extract_text() for p in pypdf.PdfReader(CV).pages)


def parse_cv(text):
    lines = text.split("\n")
    try:
        start = next(i for i, l in enumerate(lines) if l.strip() == START)
        end = next(i for i, l in enumerate(lines[start:], start) if l.strip() == END)
    except StopIteration:
        sys.exit(f"Could not find the '{START}' ... '{END}' publication block in the CV.")
    entries, cur, section = [], None, None
    for raw in lines[start:end]:
        s = raw.rstrip()
        key = nospace(s).lower()
        hit = next((t for h, t in SECTIONS if key.startswith(h)), None)
        if hit:
            section = hit
            continue
        if re.fullmatch(r"\d{1,2}", s.strip()):  # page number
            continue
        m = re.match(r"^(\d{1,3})\. (.*)", s)
        if m and (not entries or int(m.group(1)) == entries[-1]["n"] + 1):
            if section is None:
                sys.exit(f"Entry {m.group(1)} appears before any known section heading.")
            cur = {"n": int(m.group(1)), "type": section, "lines": [m.group(2)], "award": []}
            entries.append(cur)
            continue
        if cur is None:
            continue
        # Award lines are rendered after a bullet glyph that extracts as a leading space.
        if (s.startswith(" ") and s.strip()) or (cur["award"] and s.startswith("presentation")):
            cur["award"].append(s.strip())
            continue
        cur["lines"].append(s)

    for e in entries:
        t = ""
        for ln in e.pop("lines"):
            ln = ln.strip()
            if t and re.search(r"(https?:|https?://\S*[/_.\-])$", t):  # URL wrapped across lines
                t += ln
            else:
                t = f"{t} {ln}" if t else ln
        t = re.sub(r"\s+", " ", t).replace(" ,", ",").replace(" .", ".")
        t = t.replace("W ACV", "WACV").replace("A very, R.", "Avery, R.")  # PDF kerning artifacts
        e["award"] = " ".join(e["award"]) or None
        m = re.search(r"https?://\S+", t)
        e["url"] = m.group(0).rstrip(".,") if m else None
        m = re.match(r"^(.*?)\s?\(\s?(\d{4})\)\.?\s?(.*)$", t)
        if not m:
            sys.exit(f"CV entry {e['n']}: could not find '(YEAR).' after the authors:\n  {t}")
        e["authors"], e["year"], e["rest"] = m.group(1).strip(), int(m.group(2)), m.group(3)
    return entries


def split_title(rest, known_titles):
    """Split 'Title. Venue, url' into (title, venue). Known titles win."""
    nr = nospace(rest)
    for t in sorted(known_titles, key=len, reverse=True):
        if nr.startswith(nospace(t)):
            # walk forward in `rest` to the same number of non-space chars
            k, cnt = 0, 0
            while cnt < len(nospace(t)):
                if not rest[k].isspace():
                    cnt += 1
                k += 1
            return rest[:k].strip(), rest[k:].lstrip(" .,?")
    # Heuristic for new titles. The title ends at the first of:
    #   ". "  (not an abbreviation like "U.S."),
    #   ", In " / ", arXiv"  (some CV entries use a comma),
    #   "? "  but only when what follows looks like a venue, since titles such as
    #         "Pretrain Where? Investigating ..." contain a question mark.
    for m in re.finditer(r"(?<![A-Z]\.[A-Z])(?<!\b[A-Z])\. |, (?=In |arXiv )|\? ", rest):
        after = rest[m.end():]
        if m.group(0) == "? " and not (VENUE_START.match(after) or ". " not in after):
            continue
        title = rest[: m.start() + (1 if m.group(0) == "? " else 0)].strip()
        return title, after.strip()
    return rest.strip(), ""


VENUE_START = re.compile(
    r"(In |Proceedings|To appear|arXiv|ArXiv|Nature|Journal|IEEE|ACM|AAAI|International|"
    r"Neural|Transactions|Remote Sensing|Science|Frontiers|Scientific)")


def clean_venue(venue, url):
    if url:
        venue = venue.replace(url, "")
    return re.sub(r"[,.\s]+$", "", venue).strip()


# ---------------------------------------------------------------- short venue
CONFS = [
    (r"Winter Conference on Applications of Computer Vision|\bWACV\b", "WACV"),
    (r"Computer Vision and Pattern Recognition|\bCVPR\b", "CVPR"),
    (r"Neural Information Processing Systems|\bNeurIPS\b", "NeurIPS"),
    (r"International Conference on Machine Learning|\bICML\b", "ICML"),
    (r"International Conference on Learning Representations|\bICLR\b", "ICLR"),
    (r"Innovative Applications of Artificial Intelligence|\bIAAI\b", "IAAI"),
    (r"AAAI Conference|\bAAAI\b", "AAAI"),
    (r"Knowledge Discover|\bKDD\b", "KDD"),
    (r"\bSIGSPATIAL\b", "ACM SIGSPATIAL"),
    (r"ACM International Conference on Multimedia", "ACM Multimedia"),
    (r"Geoscience and Remote Sensing Symposium|\bIGARSS\b", "IGARSS"),
]


def short_venue(e):
    v, y, t = e["venue_full"], e["year"], e["type"]
    if t == "preprint" or v.lower().startswith("arxiv"):
        return "arXiv preprint" if t == "preprint" else f"arXiv {y}"
    if t == "journal":
        return f"{v.split(', ')[0]} {y}"
    for rx, name in CONFS:
        if re.search(rx, v):
            label = f"{name} {y}"
            if t == "workshop" or re.search(r"Workshop", v):
                label += " Workshops"
            if "Datasets and Benchmarks" in v:
                label += " Datasets & Benchmarks"
            if "Position Paper" in v:
                label += " Position Paper Track"
            return label
    return f"{v.split(', ')[0]} {y}"


# ---------------------------------------------------------------------- ids
STOP = {"a", "an", "the", "on", "of", "for", "to", "in", "and", "with", "how", "from",
        "is", "does", "chapter", "1", "-", "position", "paper"}


def ascii_slug(s):
    return re.sub(r"[^a-z]", "", unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode().lower())


def new_id(e, taken):
    first = next((w for w in re.findall(r"[A-Za-z0-9\-]+", e["title"]) if w.lower() not in STOP), "paper")
    base = ascii_slug(e["authors"].split(",")[0]) + str(e["year"]) + ascii_slug(first)
    pid, k = base, 2
    while pid in taken:
        pid = f"{base}_{e['type']}" if k == 2 else f"{base}_{k}"
        k += 1
    return pid


# ------------------------------------------------------------------ matching
def match_existing(entries, old):
    used, out = set(), {}
    by_key = {(norm_title(o["title"]), o.get("type")): o for o in old}
    by_title = {}
    for o in old:
        by_title.setdefault(norm_title(o["title"]), []).append(o)
    for e in entries:  # exact title + section
        o = by_key.get((norm_title(e["title"]), e["type"]))
        if o and o["id"] not in used:
            out[e["n"]] = o
            used.add(o["id"])
    for e in entries:  # exact title, section changed (e.g. preprint -> conference)
        if e["n"] in out:
            continue
        for o in by_title.get(norm_title(e["title"]), []):
            if o["id"] not in used:
                out[e["n"]] = o
                used.add(o["id"])
                break
    for e in entries:  # fuzzy title (title edited in the CV)
        if e["n"] in out:
            continue
        best, score = None, 0.0
        for o in old:
            if o["id"] in used:
                continue
            r = difflib.SequenceMatcher(None, norm_title(e["title"]), norm_title(o["title"])).ratio()
            if o.get("type") == e["type"]:
                r += 0.02
            if r > score:
                best, score = o, r
        if best and score >= 0.85:
            out[e["n"]] = best
            used.add(best["id"])
    return out, [o for o in old if o["id"] not in used]


# -------------------------------------------------------------------- bibtex
def bib_authors(authors):
    if "et al." in authors:
        return authors.split(",")[0].strip() + ", " + authors.split(",")[1].strip() + " and others"
    a = re.sub(r",?\s+and\s+", ", ", authors)
    toks = [t.strip() for t in a.split(",") if t.strip()]
    initials = re.compile(r"^(?:[A-Z][a-z]?\.?(?:[\s-]|$))+$")
    names, i = [], 0
    while i < len(toks):
        if i + 1 < len(toks) and initials.match(toks[i + 1]):
            names.append(f"{toks[i]}, {toks[i + 1]}")
            i += 2
        else:
            names.append(toks[i])
            i += 1
    return " and ".join(names)


def bib_esc(s):
    return s.replace("&", r"\&").replace("%", r"\%")


def bibtex(p):
    t, v = p["type"], p["venue_full"]
    f = {"title": "{" + bib_esc(p["title"]) + "}", "author": bib_esc(bib_authors(p["authors"])),
         "year": str(p["year"])}
    if "Dissertation" in v:
        kind = "phdthesis"
        f["school"] = v.split(", ", 1)[-1]
    elif t == "book" and v.startswith("In:"):
        kind = "incollection"
        f["booktitle"] = bib_esc(v)
    elif t == "book":
        kind = "book"  # an edited volume: the CV lists the editors
        f["editor"] = f.pop("author")
        f["publisher"] = bib_esc(v)
    elif t in ("conference", "workshop"):
        kind = "inproceedings"
        f["booktitle"] = bib_esc(v)
    elif t == "journal":
        kind = "article"
        f["journal"] = bib_esc(v.split(", ")[0])
    else:
        kind = "misc"
        f["howpublished"] = bib_esc(v)
    if p.get("paper"):
        f["url"] = p["paper"]
    if p.get("award"):
        f["note"] = bib_esc(p["award"])
    body = ",\n".join(f"  {k}={{{val}}}" for k, val in f.items())
    return f"@{kind}{{{p['id']},\n{body}\n}}\n"


# ---------------------------------------------------------------------- YAML
def dump_yaml(pubs):
    q = lambda s: json.dumps(s, ensure_ascii=False)  # JSON strings are valid YAML
    out, yr = [HEADER], None
    for p in pubs:
        if p["year"] != yr:
            yr = p["year"]
            out.append(f"\n# {'=' * 30} {yr} {'=' * 30}\n")
        lines = [f"- id: {p['id']}"]
        if p.get("recent"):
            lines.append("  recent: true")
        for k in ("title", "authors", "venue", "venue_full"):
            lines.append(f"  {k}: {q(p[k])}")
        lines += [f"  type: {p['type']}", f"  year: {p['year']}"]
        for k in ("award", "paper") + HAND_FIELDS:
            if p.get(k):
                lines.append(f"  {k}: {q(p[k])}")
        lines.append(f'  bibtex: "/files/bibtex/{p["id"]}.bib"')
        out.append("\n".join(lines) + "\n\n")
    return "".join(out).rstrip() + "\n"


# -------------------------------------------------------------- verification
def verify(pubs, text, n_cv):
    block = text[text.index(START):text.index("\n" + END + "\n")]
    # Compare with all whitespace removed so PDF line breaks/kerning don't matter.
    flat = nospace(re.sub(r"\n\d{1,2}\n", "\n", block))
    errs = []
    for p in pubs:
        if not p["venue_full"] or "http" in p["title"]:
            errs.append(f"{p['id']}: could not split title from venue: {p['title'][:90]}")
        for k in ("title", "authors", "venue_full"):
            if p[k] and nospace(p[k]) not in flat:
                errs.append(f"{p['id']}: {k} not found verbatim in CV")
        for k in ("paper", "award"):
            if p.get(k) and nospace(p[k]) not in flat:
                errs.append(f"{p['id']}: {k} not found in CV")
        if nospace(p["authors"]) + f"({p['year']})" not in flat:
            errs.append(f"{p['id']}: year {p['year']} does not follow authors in CV")
    if len(pubs) != n_cv:
        errs.append(f"{len(pubs)} YAML entries but {n_cv} numbered CV entries")
    if len({p["id"] for p in pubs}) != len(pubs):
        errs.append("duplicate ids")
    return errs


# ---------------------------------------------------------------------- main
def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dry-run", action="store_true", help="report changes without writing files")
    ap.add_argument("--thumbnails", action="store_true",
                    help="afterwards, generate thumbnails for every paper missing one")
    args = ap.parse_args()

    text = cv_text()
    entries = parse_cv(text)
    old = yaml.safe_load(PUBS.read_text()) if PUBS.exists() else []
    known = [o["title"] for o in old]
    for e in entries:
        e["title"], venue = split_title(e["rest"], known)
        e["title"] = e["title"] if e["title"].endswith("?") else e["title"].rstrip(",.")
        e["venue_full"] = clean_venue(venue, e["url"])

    matched, removed = match_existing(entries, old)
    taken = {o["id"] for o in old}
    pubs, added, changed = [], [], []
    for e in entries:
        o = matched.get(e["n"])
        p = {"id": o["id"] if o else new_id(e, taken)}
        taken.add(p["id"])
        p.update(title=e["title"], authors=e["authors"], venue_full=e["venue_full"],
                 type=e["type"], year=e["year"], award=e["award"], paper=e["url"])
        if o and o.get("venue") and o.get("venue_full") == e["venue_full"] and o.get("year") == e["year"]:
            p["venue"] = o["venue"]
        else:
            p["venue"] = short_venue(p)
        if o:
            for k in HAND_FIELDS:
                if o.get(k):
                    p[k] = o[k]
            diffs = [k for k in ("title", "authors", "venue_full", "type", "year", "award", "paper", "venue")
                     if (o.get(k) or None) != (p.get(k) or None)]
            if diffs:
                changed.append((p["id"], diffs))
        else:
            added.append(p)
        p["_n"] = e["n"]
        pubs.append(p)

    pubs.sort(key=lambda p: (-p["year"], p["_n"]))
    feat = [p for p in pubs if p.get("paper")][:RECENT_COUNT]
    for p in pubs:
        p["recent"] = p in feat
        del p["_n"]

    errs = verify(pubs, text, len(entries))

    # ------- report
    print(f"CV: {len(entries)} publications. YAML before: {len(old)} entries.")
    for p in added:
        print(f"  + {p['id']}  [{p['type']}]  venue label: \"{p['venue']}\"\n      {p['title']}")
    for o in removed:
        print(f"  - {o['id']}  (no longer in CV)  {o['title']}")
    for pid, diffs in changed:
        print(f"  ~ {pid}: {', '.join(diffs)}")
    old_recent = [o["id"] for o in old if o.get("recent")]
    new_recent = [p["id"] for p in pubs if p["recent"]]
    if old_recent != new_recent:
        print(f"  Recent work: {', '.join(new_recent)}")
    if not (added or removed or changed or old_recent != new_recent):
        print("  No changes.")
    if errs:
        print("\nCROSS-CHECK FAILED (nothing written):")
        for e in errs:
            print("  " + e)
        sys.exit(1)
    print("Cross-check against CV: OK")
    if args.dry_run:
        print("Dry run: no files written.")
        return

    PUBS.write_text(dump_yaml(pubs))
    BIB_DIR.mkdir(parents=True, exist_ok=True)
    keep = set()
    for p in pubs:
        path = BIB_DIR / f"{p['id']}.bib"
        path.write_text(bibtex(p))
        keep.add(path.name)
    for f in BIB_DIR.glob("*.bib"):
        if f.name not in keep:
            f.unlink()
    print(f"Wrote {PUBS.relative_to(REPO)} and {len(keep)} bibtex files.")
    if added:
        print("Review the new entries' venue labels above; edit `venue` in the YAML if needed.")

    if args.thumbnails:
        import subprocess
        subprocess.run([sys.executable, str(REPO / "scripts" / "paper_thumbnails.py"), "--all"], check=False)


if __name__ == "__main__":
    main()
